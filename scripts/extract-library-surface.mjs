#!/usr/bin/env node
// Extract the documentable public surface of maplibre-geoman-pro (mode names,
// the geoman.edit / geoman.layers API methods, and the library version) from
// the library SOURCE and write it to _meta/library-surface.json.
//
// This snapshot is the source of truth for scripts/check-docs.mjs, which fails
// when the docs fall behind the library. Re-run this whenever the library is
// bumped (`npm run docs:extract-surface`) so the coverage check tracks the new
// surface. Keeping the snapshot checked in lets the check run in CI without the
// library checkout present.
//
// Library location: $GEOMAN_PRO_DIR, else the sibling ../maplibre-geoman-pro.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const docsRoot = resolve(scriptDir, '..')
const libDir =
  process.env.GEOMAN_PRO_DIR ?? resolve(docsRoot, '..', 'maplibre-geoman-pro')

if (!existsSync(libDir)) {
  console.error(
    `Library source not found at "${libDir}".\n` +
      `Set GEOMAN_PRO_DIR to the maplibre-geoman-pro checkout, or run from a sibling layout.`,
  )
  process.exit(1)
}

const read = (rel) => readFileSync(resolve(libDir, rel), 'utf8')

// Pull the quoted strings out of an `export const NAME = [ ... ] as const` block.
// Spreads (e.g. `...SHAPE_NAMES`) contribute no quoted strings and are ignored.
const constArray = (src, name) => {
  const block = src.match(new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\]`))
  if (!block) throw new Error(`Could not find "export const ${name}" array`)
  return [...block[1].matchAll(/'([^']+)'/g)].map((m) => m[1])
}

const constantsSrc = read('packages/core/src/modes/constants.ts')
const shapeNames = constArray(constantsSrc, 'SHAPE_NAMES')
const extraDrawModes = constArray(constantsSrc, 'EXTRA_DRAW_MODES')
const drawModes = [...shapeNames, ...extraDrawModes]
const editModes = constArray(constantsSrc, 'EDIT_MODES')
const helperModes = constArray(constantsSrc, 'HELPER_MODES')

// Public (non-private) methods of an API class, in source order.
const publicMethods = (src) =>
  [...src.matchAll(/^ {2}(?:async )?([a-zA-Z][\w]*)\s*\(/gm)]
    .map((m) => m[1])
    .filter((name) => name !== 'constructor')

const editApiMethods = publicMethods(read('packages/core/src/core/edit-api.ts'))
const layersApiMethods = publicMethods(read('packages/core/src/core/layers-api.ts'))

// Edit-operation rejection reasons (for the operation_rejected event).
const rejectionReasonsSrc = read('packages/core/src/types/events/edit.ts')
const rejectionReasons = (() => {
  const m = rejectionReasonsSrc.match(/GmEditRejectionReason\s*=\s*([^;]+);/)
  if (!m) return []
  return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1])
})()

let libraryVersion = 'unknown'
try {
  libraryVersion = JSON.parse(read('packages/maplibre-pro/package.json')).version
} catch {
  try {
    libraryVersion = JSON.parse(read('package.json')).version
  } catch {
    /* leave unknown */
  }
}

const surface = {
  // generated by scripts/extract-library-surface.mjs — do not edit by hand
  libraryVersion,
  modes: { draw: drawModes, edit: editModes, helper: helperModes },
  api: { edit: editApiMethods, layers: layersApiMethods },
  rejectionReasons,
}

const metaDir = resolve(docsRoot, '_meta')
if (!existsSync(metaDir)) mkdirSync(metaDir)
const outFile = resolve(metaDir, 'library-surface.json')
writeFileSync(outFile, JSON.stringify(surface, null, 2) + '\n')

console.log(`Wrote ${outFile} from library @ ${libraryVersion}`)
console.log(
  `  draw: ${drawModes.length}, edit: ${editModes.length}, helper: ${helperModes.length} modes; ` +
    `edit API: ${editApiMethods.length}, layers API: ${layersApiMethods.length} methods`,
)
